import { expect, test } from '@playwright/test';

test('attendance calculator explains savings and keeps the case study confidential', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('.project-card h3').first()).toHaveText('Attendance & HR Core');
  await page.getByRole('link', { name: 'View Attendance & HR Core', exact: true }).click();
  await page.getByRole('button', { name: 'Simulate time-in' }).click();
  await expect(page.locator('[data-recognition-status]')).toContainText('Alex Cruz / Time-in recorded');
  await expect(page.getByRole('button', { name: 'Replay time-in' })).toBeEnabled();
  const results = page.locator('[data-attendance-results]');
  await expect(results).toContainText('6 hr 43 min saved');
  await page.getByLabel('Employees', { exact: true }).fill('10');
  await page.getByLabel('Working days', { exact: true }).fill('1');
  await expect(results).toContainText('1.8 min saved');
  await expect(results).toContainText('20 actions');
  await page.getByLabel('Explore a 60-second', { exact: false }).check();
  await expect(results).toContainText('19.3 min saved');
  await expect(results).toContainText('does not represent the typical employee');
  await expect(page.locator('#attendance-before')).toBeDisabled();
  await page.getByLabel('Employees', { exact: true }).fill('');
  await expect(results).toContainText('Enter a whole employee count');
  await expect(page.getByRole('link', { name: 'View repository' })).toHaveCount(0);
  await expect(page.locator('.ecosystem-map')).toContainText('Work in progress');
  await expect(page.locator('.ecosystem-column')).toHaveCount(3);
  await expect(page.locator('.ecosystem-column li')).toHaveCount(13);
  await expect(page.locator('.hr-stack')).toContainText('SFace embeddings');
  await expect(page.locator('.hr-itinerary')).toContainText('remote and deployed employees');
  await page.getByRole('button', { name: 'Low accuracy', exact: true }).click();
  await expect(page.locator('[data-location-explanation]')).toContainText('flags low accuracy');
  await expect(page.locator('.itinerary-location-demo')).toHaveAttribute('data-scenario', 'imprecise');
  await page.getByRole('button', { name: 'Cached location', exact: true }).click();
  await expect(page.locator('[data-location-explanation]')).toContainText('Last known is different from live');
  await page.getByRole('button', { name: 'GPS fix', exact: true }).click();
  await expect(page.locator('[data-location-explanation]')).toContainText('Live device location');
  const employeeSearch = page.getByRole('searchbox', { name: 'Search employees' });
  await employeeSearch.fill('Jamie');
  await page.getByRole('button', { name: 'Jamie Lee', exact: true }).click();
  await expect(page.locator('[data-employee-connections]')).toContainText('Field tablet / Assigned');
  await expect(page.locator('[data-employee-connections]')).toContainText('Deployment brief / Reviewed');
  await expect(page.locator('[data-demo-employee]:visible')).toHaveCount(1);
  await expect(page.locator('[data-employee-count]')).toHaveText('1 fictional employee');
  await expect(results).toContainText('Enter a whole employee count');
  await employeeSearch.fill('no-such-person');
  await expect(page.locator('[data-employee-count]')).toContainText('No matches');
  await employeeSearch.fill('');
  await expect(page.locator('[data-demo-employee]:visible')).toHaveCount(4);
  await expect(page.locator('main')).not.toContainText(/laragon|attendance_monitoring|employee_id|is_hr/);
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1);
  await page.getByRole('link', { name: 'Explore inventory' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Inventory Tracking System');
});
